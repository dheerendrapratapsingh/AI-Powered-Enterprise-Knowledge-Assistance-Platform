import requests
import json
import re
from typing import Generator
from app.config import settings

def check_gemini_available() -> bool:
    return bool(settings.GEMINI_API_KEY and settings.GEMINI_API_KEY.strip())

def check_ollama_health() -> bool:
    try:
        response = requests.get(f"{settings.OLLAMA_BASE_URL}/api/tags", timeout=2)
        return response.status_code == 200
    except requests.RequestException:
        return False

# ==================== Google Gemini 2.0 Flash ====================

def _generate_gemini(prompt: str) -> dict:
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{settings.GEMINI_MODEL}:generateContent?key={settings.GEMINI_API_KEY}"
    payload = {
        "contents": [
            {
                "parts": [{"text": prompt}]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 2048
        }
    }
    
    response = requests.post(url, json=payload, timeout=20)
    if response.status_code != 200:
        raise RuntimeError(f"Gemini API returned status {response.status_code}: {response.text}")
        
    data = response.json()
    candidates = data.get("candidates", [])
    if not candidates:
        return {"answer": "No response generated by AI.", "response_type": "answer", "sources": []}
        
    parts = candidates[0].get("content", {}).get("parts", [])
    raw_text = "".join([p.get("text", "") for p in parts])
    
    # Try parsing JSON if prompt requested JSON
    cleaned = raw_text.strip()
    if cleaned.startswith("```json"):
        cleaned = re.sub(r"^```json\s*", "", cleaned)
        cleaned = re.sub(r"\s*```$", "", cleaned)
    elif cleaned.startswith("```"):
        cleaned = re.sub(r"^```\s*", "", cleaned)
        cleaned = re.sub(r"\s*```$", "", cleaned)
        
    try:
        parsed = json.loads(cleaned)
        if isinstance(parsed, dict) and "answer" in parsed:
            return parsed
    except Exception:
        pass
        
    return {
        "answer": raw_text,
        "response_type": "answer",
        "sources": []
    }

def _stream_gemini_tokens(prompt: str) -> Generator[str, None, None]:
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{settings.GEMINI_MODEL}:streamGenerateContent?alt=sse&key={settings.GEMINI_API_KEY}"
    payload = {
        "contents": [
            {
                "parts": [{"text": prompt}]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 2048
        }
    }
    
    response = requests.post(url, json=payload, stream=True, timeout=30)
    if response.status_code != 200:
        raise RuntimeError(f"Gemini stream error ({response.status_code}): {response.text}")
        
    for line in response.iter_lines():
        if line:
            decoded = line.decode("utf-8").strip()
            if decoded.startswith("data: "):
                data_str = decoded[6:].strip()
                if data_str == "[DONE]":
                    break
                try:
                    data = json.loads(data_str)
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        for p in parts:
                            text_piece = p.get("text", "")
                            if text_piece:
                                yield text_piece
                except Exception:
                    continue

# ==================== Local Ollama Engine ====================

def _generate_ollama(prompt: str) -> dict:
    if not check_ollama_health():
        raise RuntimeError("Local Ollama service is not running on " + settings.OLLAMA_BASE_URL)
        
    payload = {
        "model": settings.OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "format": "json"
    }
    
    response = requests.post(f"{settings.OLLAMA_BASE_URL}/api/generate", json=payload, timeout=45)
    if response.status_code != 200:
        raise RuntimeError(f"Ollama generation failed: {response.text}")
        
    result_text = response.json().get("response", "{}")
    try:
        parsed = json.loads(result_text)
        return parsed
    except json.JSONDecodeError:
        return {
            "answer": result_text,
            "response_type": "answer",
            "sources": []
        }

def _stream_ollama_tokens(prompt: str) -> Generator[str, None, None]:
    if not check_ollama_health():
        raise RuntimeError("Local Ollama service is not running on " + settings.OLLAMA_BASE_URL)
        
    payload = {
        "model": settings.OLLAMA_MODEL,
        "prompt": prompt,
        "stream": True
    }
    
    response = requests.post(f"{settings.OLLAMA_BASE_URL}/api/generate", json=payload, stream=True, timeout=45)
    if response.status_code != 200:
        raise RuntimeError(f"Ollama generation failed: {response.text}")
        
    for line in response.iter_lines():
        if line:
            chunk = json.loads(line.decode("utf-8"))
            yield chunk.get("response", "")
            if chunk.get("done", False):
                break

# ==================== Hybrid Unified Public Interface ====================

def generate_response(prompt: str) -> dict:
    if check_gemini_available():
        try:
            return _generate_gemini(prompt)
        except Exception as e:
            print(f"[LLM] Gemini request failed, trying Ollama fallback: {e}")
            if check_ollama_health():
                return _generate_ollama(prompt)
            raise RuntimeError(f"Gemini failed ({e}) and local Ollama is offline.")
            
    if check_ollama_health():
        return _generate_ollama(prompt)
        
    raise RuntimeError("No AI engine available. Please provide GEMINI_API_KEY in .env or run local Ollama.")

def stream_response_tokens(prompt: str) -> Generator[str, None, None]:
    if check_gemini_available():
        try:
            for token in _stream_gemini_tokens(prompt):
                yield token
            return
        except Exception as e:
            print(f"[LLM] Gemini streaming failed, attempting Ollama fallback: {e}")
            if check_ollama_health():
                for token in _stream_ollama_tokens(prompt):
                    yield token
                return
            raise RuntimeError(f"Gemini streaming failed ({e}) and local Ollama is offline.")
            
    if check_ollama_health():
        for token in _stream_ollama_tokens(prompt):
            yield token
        return
        
    raise RuntimeError("No AI engine available. Please configure GEMINI_API_KEY in .env or start local Ollama.")
